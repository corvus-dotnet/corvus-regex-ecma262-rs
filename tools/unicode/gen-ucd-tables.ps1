<#
.SYNOPSIS
    Writes corvus-regex-ecma262/src/tables<major>.rs, the Unicode data of one version for the crate.

.DESCRIPTION
    The crate takes every Unicode property its engine reads from the tables this script writes, and nothing from the
    Rust standard library or from the regex crate, so that its answers do not depend on the toolchain or on the
    versions of its dependencies. It carries the tables of each version of Unicode it offers (13.0.0, 17.0.0 and
    18.0.0), one module for each, and ucd.rs reads the one a pattern was compiled for.

    The source is unicodetables.rs of the regress crate, which its gen-unicode writes from the Unicode Character
    Database. regress's gen-unicode reads the database from a directory named for 17.0.0 (/tmp/ucd-17.0.0), so the
    tables of another version are made by pointing that directory at that version's files, running gen-unicode and
    rustfmt, and giving this script the result. The script runs two steps:

    - gen-ucd-go-form.ps1, the generator of the Go module's tables (src-go/corvus-json-schema/internal/ucd of
      Corvus.JsonSchema, where the chain began), writes the tables in that module's form: the General_Category values,
      the binary properties, the Script values, the Script_Extensions ranges that differ from the Script ranges, the
      simple case folding and the simple uppercase mapping, with each value that follows from others checked and
      left out;
    - this script changes that form into Rust and nothing else: the same tables with the same ranges in the same
      order, and the same lookups by name.

    Run on regress 0.12.0's tables of Unicode 17.0.0, the two steps give tables17.rs byte for byte as the crate
    shipped it before it carried other versions. The Go engine and the other ports take their tables from these.

.PARAMETER RegressTables
    The path of unicodetables.rs written by regress's gen-unicode for the version.

.PARAMETER UnicodeVersion
    The version of Unicode of the source, such as 18.0.0.

.PARAMETER GoTables
    A file in the Go module's form to convert in place of running the first step on -RegressTables.

.PARAMETER Output
    The file to write. The default is corvus-regex-ecma262/src/tables<major>.rs.

.EXAMPLE
    pwsh tools/unicode/gen-ucd-tables.ps1 -RegressTables unicodetables-18.0.0.rs -UnicodeVersion 18.0.0
#>
param(
    [string]$RegressTables = '',
    [string]$UnicodeVersion = '17.0.0',
    [string]$GoTables = '',
    [string]$Output = ''
)

$ErrorActionPreference = 'Stop'
if (-not $Output) {
    $Output = Join-Path $PSScriptRoot '..' '..' 'corvus-regex-ecma262' 'src' "tables$($UnicodeVersion.Split('.')[0]).rs"
}

$temp = $null
if (-not $GoTables) {
    if (-not $RegressTables) { throw 'Give -RegressTables (or -GoTables).' }
    $temp = [System.IO.Path]::GetTempFileName()
    & (Join-Path $PSScriptRoot 'gen-ucd-go-form.ps1') -RegressTables $RegressTables -UnicodeVersion $UnicodeVersion -Output $temp *> $null
    $GoTables = $temp
}

$lines = [System.IO.File]::ReadAllLines((Resolve-Path $GoTables))
if ($temp) { Remove-Item $temp }

# gcLu becomes GC_LU, binAsciiHexDigit becomes BIN_ASCII_HEX_DIGIT.
function ConvertTo-Constant([string]$name) {
    return ([regex]::Replace($name, '(?<=[a-z0-9])(?=[A-Z])', '_')).ToUpperInvariant()
}

$functions = @{
    'categoryTable'         = 'category_table'
    'binaryTable'           = 'binary_table'
    'scriptTable'           = 'script_table'
    'scriptExtensionsTable' = 'script_extensions_table'
}

$out = [System.Text.StringBuilder]::new()
function Add([string]$text) { [void]$out.Append($text).Append("`n") }

$version = $null
$mode = ''
foreach ($line in $lines) {
    if ($line -match '^// Code generated') {
        $from = if ($line -match 'Unicode (\S+) property tables') { $Matches[1] } else { $UnicodeVersion }
        Add "// Code generated by tools/unicode/gen-ucd-tables.ps1 from the Unicode $from property tables of the regress"
        Add '// crate (gen-unicode), through the Go module''s form (gen-ucd-go-form.ps1). DO NOT EDIT.'
        continue
    }
    if ($line -match '^package ') {
        Add 'use super::ucd::{CaseRange, Table};'
        continue
    }
    if ($line -match '^const Version = "(.*)"$') {
        $version = $Matches[1]
        Add "pub(crate) const VERSION: &str = `"$version`";"
        continue
    }
    if ($line -match '^func (\w+)\(name string\) \*Table \{$') {
        Add "pub(super) fn $($functions[$Matches[1]])(name: &str) -> Option<&'static Table> {"
        $mode = 'lookup'
        continue
    }
    if ($mode -eq 'lookup') {
        if ($line -match '^\tswitch name \{$') { Add '    match name {'; continue }
        if ($line -match '^\tcase (.*):$') {
            $names = ($Matches[1] -split ', ') -join ' | '
            $pending = $names
            continue
        }
        if ($line -match '^\t\treturn &(\w+)$') {
            Add "        $pending => Some(&$(ConvertTo-Constant $Matches[1])),"
            continue
        }
        if ($line -match '^\t\}$') { Add '        _ => None,'; Add '    }'; continue }
        if ($line -match '^\treturn nil$') { continue }
        if ($line -eq '}') { Add '}'; $mode = ''; continue }
        throw "Unexpected line in a lookup: $line"
    }
    if ($line -match '^var scriptNames = ') { Add 'pub(super) static SCRIPT_NAMES: &[&[&str]] = &['; $mode = 'names2'; continue }
    if ($line -match '^var binaryNames = ') { Add 'pub(super) static BINARY_NAMES: &[&str] = &['; $mode = 'names1'; continue }
    if ($mode -eq 'names2') {
        if ($line -eq '}') { Add '];'; $mode = ''; continue }
        if ($line -match '^\t\{(.*)\},$') { Add "    &[$($Matches[1])],"; continue }
        throw "Unexpected line in the script names: $line"
    }
    if ($mode -eq 'names1') {
        if ($line -eq '}') { Add '];'; $mode = ''; continue }
        Add ('    ' + $line.Trim())
        continue
    }
    if ($line -match '^var (\w+) = Table\{$') {
        Add "pub(super) static $(ConvertTo-Constant $Matches[1]): Table = Table {"
        $mode = 'table'
        $seen = @{}
        continue
    }
    if ($mode -eq 'table') {
        if ($line -match '^\t(r16|r32): \[\]uint(16|32)\{$') { Add "    $($Matches[1]): &["; $seen[$Matches[1]] = $true; continue }
        if ($line -match '^\t\},$') { Add '    ],'; continue }
        if ($line -eq '}') {
            if (-not $seen['r16']) { Add '    r16: &[],' }
            if (-not $seen['r32']) { Add '    r32: &[],' }
            Add '};'
            $mode = ''
            continue
        }
        Add ('        ' + $line.Trim())
        continue
    }
    if ($line -match '^var (caseFolds|upperCases) = \[\]caseRange\{$') {
        Add "pub(super) static $(ConvertTo-Constant $Matches[1]): &[CaseRange] = &["
        $mode = 'cases'
        continue
    }
    if ($mode -eq 'cases') {
        if ($line -eq '}') { Add '];'; $mode = ''; continue }
        if ($line -match '^\t\{(\S+), (\S+), (\S+), (\S+)\},$') {
            Add "    CaseRange { first: $($Matches[1]), delta: $($Matches[2]), length: $($Matches[3]), mask: $($Matches[4]) },"
            continue
        }
        throw "Unexpected line in a case table: $line"
    }
    if ($line -match '^//' -or $line -eq '') { Add $line; continue }
    throw "Unexpected line: $line"
}
if (-not $version) { throw 'The source has no version.' }

# One newline at the end of the file.
[System.IO.File]::WriteAllText($Output, $out.ToString().TrimEnd("`n") + "`n")
Write-Host "Wrote $Output (Unicode $version)."
