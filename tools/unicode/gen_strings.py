#!/usr/bin/env python3
"""Writes strings<major>.rs, the data behind the properties of strings that a pattern with the v flag may name
(\\p{RGI_Emoji} and the six it is the union of), from the two emoji sequence files of the Unicode Character Database.

ECMA-262 lets \\p{...} name seven properties of strings with the v flag: Basic_Emoji, Emoji_Keycap_Sequence,
RGI_Emoji_Modifier_Sequence, RGI_Emoji_Flag_Sequence, RGI_Emoji_Tag_Sequence, RGI_Emoji_ZWJ_Sequence and RGI_Emoji,
which is the union of the other six. The first five are in emoji-sequences.txt and the sixth in
emoji-zwj-sequences.txt. Basic_Emoji has single code points as well as sequences; the others hold sequences only.

Each property is written as two texts: its single code points as hexadecimal ranges, and its sequences as
hexadecimal code points, a space between the code points of a sequence and a semicolon between sequences. This is
the generator of the .NET reference engine (tools/unicode/gen-ecma-unicode-strings.ps1) in Python.

    python3 tools/unicode/gen_strings.py <emoji-sequences.txt> <emoji-zwj-sequences.txt> corvus-regex-ecma262/src/strings<major>.rs
"""
import re
import sys

PROPERTIES = [
    "Basic_Emoji",
    "Emoji_Keycap_Sequence",
    "RGI_Emoji_Modifier_Sequence",
    "RGI_Emoji_Flag_Sequence",
    "RGI_Emoji_Tag_Sequence",
    "RGI_Emoji_ZWJ_Sequence",
]


def main():
    seq_file, zwj_file = sys.argv[1], sys.argv[2]
    output = sys.argv[3]
    code_points = {p: [] for p in PROPERTIES}
    sequences = {p: [] for p in PROPERTIES}
    versions = set()
    for path in (seq_file, zwj_file):
        for line in open(path, encoding="utf-8"):
            m = re.match(r"^# Version: (.*)$", line)
            if m:
                versions.add(m.group(1).strip())
                continue
            text = line.split("#", 1)[0].strip()
            if not text:
                continue
            fields = text.split(";")
            value, name = fields[0].strip(), fields[1].strip()
            if name not in code_points:
                raise SystemExit(f"Unknown property {name} in {path}.")
            if re.fullmatch(r"[0-9A-F]+\.\.[0-9A-F]+", value) or re.fullmatch(r"[0-9A-F]+", value):
                code_points[name].append(value)
            elif re.fullmatch(r"[0-9A-F]+( +[0-9A-F]+)+", value):
                sequences[name].append(" ".join(value.split()))
            else:
                raise SystemExit(f"Unreadable value '{value}' in {path}.")
    if len(versions) != 1:
        raise SystemExit("The two files have no version, or not the same one.")
    version = versions.pop()
    out = []
    out.append(f"// Generated by tools/unicode/gen_strings.py from emoji-sequences.txt and emoji-zwj-sequences.txt of Unicode {version}.")
    out.append("// DO NOT EDIT.")
    out.append("")
    out.append("/// The version of Unicode the properties of strings are from.")
    out.append(f'pub(crate) const VERSION: &str = "{version}";')
    out.append("")
    out.append("/// Each property of strings but `RGI_Emoji` (the union of them all): its name, its single code points as")
    out.append("/// hexadecimal ranges, and its sequences as hexadecimal code points, a space between the code points of a sequence")
    out.append("/// and a semicolon between sequences.")
    out.append("pub(crate) static PROPERTIES: [(&str, &str, &str); 6] = [")
    for p in PROPERTIES:
        out.append(f'    ("{p}", "{" ".join(code_points[p])}", "{";".join(sequences[p])}"),')
    out.append("];")
    open(output, "w", encoding="utf-8").write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
