<#
.SYNOPSIS
    Writes corvus-regex-ecma262/src/es2020.rs, the Unicode property names and values that the grammar of ECMAScript
    2020 knows, from es2020-properties.json of the test data.

.DESCRIPTION
    ECMAScript 2020 (ECMA-262, 11th edition) closes the names a \p{...} escape may use: an implementation "must not
    support" names other than those of its tables of non-binary properties, binary properties, General_Category values
    and Script values (section 21.2.2.8.4). es2020-properties.json of the test data repository
    (corvus-dotnet/ecma262-regex-test-data) holds every name and alias of those four tables, taken from tc39/ecma262
    at the tag es2020. The test data's edition overlay is made from the same file, and so are the tables of the .NET
    reference engine (Es2020Properties.cs), so the engines and the data agree.

.PARAMETER Properties
    The path of es2020-properties.json.

.PARAMETER Output
    The file to write. The default is corvus-regex-ecma262/src/es2020.rs.

.EXAMPLE
    pwsh tools/unicode/gen-es2020-properties.ps1 -Properties ../ecma262-regex-test-data/es2020-properties.json
#>
param(
    [Parameter(Mandatory = $true)][string]$Properties,
    [string]$Output = ''
)

$ErrorActionPreference = 'Stop'

if (-not $Output) {
    $Output = Join-Path $PSScriptRoot '..' '..' 'corvus-regex-ecma262' 'src' 'es2020.rs'
}

$tables = Get-Content -Raw (Resolve-Path $Properties) | ConvertFrom-Json
$lines = [System.Collections.Generic.List[string]]::new()

function Add-Names([string]$function, [string]$summary, [object[]]$names) {
    [string[]]$sorted = @($names)
    [Array]::Sort($sorted, [StringComparer]::Ordinal)
    $lines.Add("/// $summary")
    $lines.Add("fn $function(name: &str) -> bool {")
    $lines.Add('    matches!(')
    $lines.Add('        name,')
    for ($k = 0; $k -lt $sorted.Length; $k++) {
        $lines.Add("        `"$($sorted[$k])`"" + $(if ($k -lt $sorted.Length - 1) { ' |' } else { '' }))
    }
    $lines.Add('    )')
    $lines.Add('}')
    $lines.Add('')
}

$lines.Add('// Code generated by tools/unicode/gen-es2020-properties.ps1 from es2020-properties.json of the test data. DO NOT EDIT.')
$lines.Add('')
$lines.Add('//! The Unicode property names and values of the tables of ECMAScript 2020 (ECMA-262, 11th edition), the only ones')
$lines.Add('//! its grammar knows whatever the version of Unicode: tc39/ecma262 at the tag es2020, every name and alias of each.')
$lines.Add('')
$lines.Add('/// Whether the expression between the braces of `\p{...}` names a property, and a value of it, of the tables: a name')
$lines.Add('/// and a value joined by `=`, or the lone name of a General_Category value or of a binary property.')
$lines.Add('pub(crate) fn has(expr: &str) -> bool {')
$lines.Add("    match expr.split_once('=') {")
$lines.Add('        None => category(expr) || binary(expr),')
$lines.Add('        Some(("General_Category" | "gc", value)) => category(value),')
$lines.Add('        Some((name, value)) => non_binary(name) && script(value),')
$lines.Add('    }')
$lines.Add('}')
$lines.Add('')
Add-Names 'non_binary' 'The non-binary properties.' $tables.nonbinary
Add-Names 'binary' 'The binary properties.' $tables.binary
Add-Names 'category' 'The values of General_Category.' $tables.general_category
Add-Names 'script' 'The values of Script and Script_Extensions.' $tables.script

[System.IO.File]::WriteAllText([System.IO.Path]::GetFullPath($Output), ($lines -join "`n").TrimEnd() + "`n")
Write-Host "Wrote $Output"
